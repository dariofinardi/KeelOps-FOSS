/** Le lingue del core, italiano compreso (la chiave È l'italiano). */
const CATALOGHI: Record<string, Record<string, string>> = { en: EN, fr: FR, de: DE, es: ES, pt: PT };
const LOCALI: Record<string, string> = {
  it: "it-IT",
  en: "en-GB",
  fr: "fr-FR",
  de: "de-DE",
  es: "es-ES",
  pt: "pt-PT",
};

function lingua(): string {
  let saved: string | null = null;
  try {
    saved = localStorage.getItem("kancrm-lang");
  } catch {
    saved = null;
  }
  const raw = saved && saved !== "auto" ? saved : navigator.language;
  return (raw ?? "it").slice(0, 2).toLowerCase();
}

export const LANG = lingua();

/** `t("chiave", { name })`: la chiave è la frase italiana. */
export function t(key: string, params?: Record<string, string | number>): string {
  const base = CATALOGHI[LANG]?.[key] ?? key;
  return params
    ? base.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(params[name] ?? ""))
    : base;
}

/** Data corta nella lingua della pagina, dal giorno ISO. */
export function formatDate(day: string): string {
  const [y, m, d] = day.split("-").map(Number);
  if (!y || !m || !d) return day;
  return new Intl.DateTimeFormat(LOCALI[LANG] ?? "it-IT", {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
  }).format(new Date(Date.UTC(y, m - 1, d)));
}

/** Oggi nel fuso aziendale (Europe/Rome), come `todayISO` del core. */
export function todayISO(): string {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: "Europe/Rome",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(new Date());
}
